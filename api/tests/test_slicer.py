# --- API ---------------------------------------------------------------------


def _upload(client, data: bytes | None = None) -> str:
    data = data or box_stl()
    r = client.post("/api/v1/uploads", files={"file": ("box.stl", data, "model/stl")})
    assert r.status_code == 201
    return r.json()["id"]


def test_materials_endpoint(client):
    assert client.get("/api/v1/materials").json()["materials"][:3] == ["PLA", "PETG", "ABS"]


def test_slice_api_sync(client, fake_slicer):
    upload_id = _upload(client)

    r = client.get(f"/api/v1/uploads/{upload_id}/slice")
    assert r.status_code == 404

    r = client.post(f"/api/v1/uploads/{upload_id}/slice", json={"material": "petg"})
    assert r.status_code == 202, r.text
    rec = r.json()
    assert rec["status"] == "done"
    assert rec["material"] == "PETG"
    assert rec["key"] == "PETG"
    assert rec["result"]["filament_g"] > 0
    assert rec["result"]["print_time_s"] > 0
    assert rec["finished_at"]

    # повторный запрос отдаёт сохранённое, без пересчёта
    r2 = client.get(f"/api/v1/uploads/{upload_id}/slice", params={"material": "PETG"})
    assert r2.status_code == 200
    assert r2.json() == rec
    r3 = client.post(f"/api/v1/uploads/{upload_id}/slice", json={"material": "PETG"})
    assert r3.json() == rec

    # с поддержками — отдельная запись
    r4 = client.post(
        f"/api/v1/uploads/{upload_id}/slice", json={"material": "PETG", "supports": True}
    )
    assert r4.json()["key"] == "PETG_supports"
    assert r4.json()["result"]["filament_g"] > rec["result"]["filament_g"]


