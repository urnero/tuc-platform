# --- parse_time ---------------------------------------------------------------


@pytest.mark.parametrize(
    "text, seconds",
    [
        ("30s", 30),
        ("45m 12s", 45 * 60 + 12),
        ("1h 2m 3s", 3723),
        ("2d 3h 4m 5s", 2 * 86400 + 3 * 3600 + 4 * 60 + 5),
        ("3h", 3 * 3600),
        ("  1h 0m 0s ", 3600),
    ],
)
def test_parse_time(text, seconds):
    assert parse_time(text) == seconds


def test_parse_time_bad():
    with pytest.raises(SlicerError):
        parse_time("скоро")


# --- parse_gcode --------------------------------------------------------------


def test_parse_gcode_sample():
    parsed = parse_gcode(SAMPLE_GCODE)
    assert parsed["print_time_s"] == 3723
    assert parsed["filament_g"] == 3.7
    assert parsed["filament_mm"] == 1234.6
    assert parsed["slicer_version"].startswith("generated by PrusaSlicer 2.8.1")


def test_parse_gcode_multi_material_sums():
    text = SAMPLE_GCODE.replace(
        "; total filament used [g] = 3.70", "; total filament used [g] = 3.70, 1.30"
    )
    assert parse_gcode(text)["filament_g"] == 5.0


def test_parse_gcode_without_totals():
    with pytest.raises(SlicerError):
        parse_gcode("G28\nG1 X1\n")


