def test_slice_api_error_is_recorded(client, fake_slicer, monkeypatch):
    """Слайсер упал → статус error с текстом, повторный POST пробует снова."""
    upload_id = _upload(client)
    monkeypatch.setattr(settings, "prusa_slicer_bin", "/nonexistent/prusa-slicer")
    r = client.post(f"/api/v1/uploads/{upload_id}/slice", json={"material": "ABS"})
