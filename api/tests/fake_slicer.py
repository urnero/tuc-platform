#!/usr/bin/env python3
"""Подделка PrusaSlicer для тестов: принимает те же аргументы и пишет G-code с итогами.

Граммы считаем из размера STL-файла, чтобы разные модели давали разные числа.
Если передан --support-material — добавляем пластика и времени.
Если входной файл называется broken.stl — падаем, как упал бы настоящий слайсер.
Файл flat*.stl или переменная FAKE_SLICER_FLAT=1 — модель без нависаний:
даже с --support-material поддержек в G-code нет.
"""

import os
import sys
from pathlib import Path


def main(argv: list[str]) -> int:
    args = argv[1:]
    out = Path(args[args.index("--output") + 1])
    model = Path(args[-1])
    if model.name.startswith("broken"):
        print("Error: failed to load model", file=sys.stderr)
        return 1
    scale = float(args[args.index("--scale") + 1]) if "--scale" in args else 1.0
    supports = "--support-material" in args and not (
        model.name.startswith("flat") or os.environ.get("FAKE_SLICER_FLAT")
    )
    size = model.stat().st_size
    grams = round(size / 100.0 * scale * (1.3 if supports else 1.0), 2)
    seconds = int(size * 2 * scale * (1.5 if supports else 1.0))
    h, rest = divmod(seconds, 3600)
    m, s = divmod(rest, 60)
    out.parent.mkdir(parents=True, exist_ok=True)
    support_lines = ";TYPE:Support material\nG1 X12 Y12\n" if supports else ""
    out.write_text(
        "; generated by PrusaSlicer 2.8.1 (fake) on 2026-10-18\n"
        "G28\nG1 X10 Y10\n"
        + support_lines
        + f"; filament used [mm] = {grams * 400:.2f}\n"
        f"; filament used [g] = {grams:.2f}\n"
        f"; total filament used [g] = {grams:.2f}\n"
        f"; estimated printing time (normal mode) = {h}h {m}m {s}s\n",
        "utf-8",
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
