"""Расчёт печати через PrusaSlicer CLI (B04).

Что делает:
1. Собирает команду `prusa-slicer --export-gcode ...` с профилями из `profiles/`
   (принтер + режим печати + материал), масштабом единиц и поддержками.
2. Запускает слайсер, ждёт G-code.
3. Из комментариев в конце G-code достаёт время печати и граммы пластика.

Слайсер пишет в конец файла строки вида:
    ; filament used [mm] = 1234.56
    ; filament used [g] = 3.70
    ; total filament used [g] = 3.70
    ; estimated printing time (normal mode) = 1h 2m 3s

Сам PrusaSlicer стоит только в контейнере worker (worker/Dockerfile).
В тестах вместо него — маленький скрипт, который пишет такой же G-code (tests/fake_slicer.py).
"""

import re
import shlex
import subprocess
from dataclasses import asdict, dataclass
from pathlib import Path

from app import materials
from app.config import settings
from app.meshcheck import UNITS

# Список материалов — config/materials.yaml (B44): FDM-материалы, у каждого
# profiles/filament/<материал>.ini. Смолы (SLA) слайсер не считает — они «по запросу».

# «1d 2h 3m 4s» / «45m 12s» / «30s» → секунды
_TIME_RE = re.compile(r"(?:(\d+)d\s*)?(?:(\d+)h\s*)?(?:(\d+)m\s*)?(?:(\d+)s)?")


class SlicerError(RuntimeError):
    """Слайсер не отработал: нет бинарника, нет профиля, упал или не выдал цифры."""


@dataclass
class SliceResult:
    material: str
    supports: bool
    print_time_s: int  # время печати, секунд
    filament_g: float  # пластика, грамм
    filament_mm: float  # пластика, мм нити
    layer_height_mm: float | None  # высота слоя из профиля (для справки)
    slicer_version: str  # строка «generated by PrusaSlicer 2.8.1 ...», если нашли

    @property
    def print_time_h(self) -> float:
        return round(self.print_time_s / 3600.0, 3)

    def to_dict(self) -> dict:
        d = asdict(self)
        d["print_time_h"] = self.print_time_h
        return d


# --- профили ---------------------------------------------------------------


def profiles_dir() -> Path:
    return settings.profiles_dir


def check_material(material: str) -> None:
    """Материал считается слайсером? Нет — SlicerError с понятным текстом."""
    allowed = materials.sliceable()
    if material in allowed:
        return
    if material in materials.on_request():
        raise SlicerError(
            f"{material} — смола, её цену называем вручную: оставьте заявку, ответим в течение дня."
        )
    raise SlicerError(f"Материал: {', '.join(allowed)}.")


def profile_paths(material: str) -> list[Path]:
    """Три ini-файла, которые загружаем в слайсер по порядку: принтер, печать, материал."""
    material = material.upper()
    check_material(material)
    paths = [
        profiles_dir() / "printer.ini",
        profiles_dir() / "print.ini",
        profiles_dir() / "filament" / f"{material}.ini",
    ]
    for p in paths:
        if not p.is_file():
            raise SlicerError(f"Нет профиля слайсера: {p}")
    return paths


def read_ini_value(path: Path, key: str) -> str | None:
    """Достаёт `key = value` из ini-профиля PrusaSlicer (без секций, просто строки)."""
    for line in path.read_text("utf-8").splitlines():
        if "=" in line and line.split("=", 1)[0].strip() == key:
            return line.split("=", 1)[1].strip()
    return None


# --- команда ---------------------------------------------------------------


def build_command(
    model_path: Path,
    gcode_path: Path,
    material: str,
    units: str = "mm",
    supports: bool = False,
    print_bed: tuple[float, float, float] | None = None,
) -> list[str]:
    """Собирает аргументы для PrusaSlicer. Отдельная функция — чтобы её проверял тест."""
    if units not in UNITS:
        raise SlicerError(f"Единицы: {', '.join(UNITS)}.")
    cmd = shlex.split(settings.prusa_slicer_bin)  # может быть «путь --appimage-extract-and-run»
    cmd += ["--export-gcode"]
    for p in profile_paths(material):
        cmd += ["--load", str(p)]
    if UNITS[units] != 1.0:
        cmd += ["--scale", str(UNITS[units])]  # файл в дюймах → умножаем на 25.4
    bed = print_bed or settings.print_bed
    cmd += ["--center", f"{bed[0] / 2:g},{bed[1] / 2:g}"]  # ставим модель в центр стола
    if supports:
        cmd += ["--support-material"]
    cmd += ["--output", str(gcode_path), str(model_path)]
    return cmd


# --- разбор G-code ----------------------------------------------------------


def parse_time(text: str) -> int:
    """«1h 2m 3s» → 3723. Пустая или непонятная строка → ошибка."""
    m = _TIME_RE.fullmatch(text.strip())
    if not m or not any(m.groups()):
        raise SlicerError(f"Не понял время печати: «{text}»")
    d, h, mi, s = (int(g) if g else 0 for g in m.groups())
    return d * 86400 + h * 3600 + mi * 60 + s


def parse_gcode(text: str) -> dict:
    """Из комментариев G-code → словарь: print_time_s, filament_g, filament_mm, slicer_version.

    Смотрим только последние 300 строк — там итоги. Для многоматериальной печати
    PrusaSlicer пишет «total filament used [g]» — берём его, если есть.
    """
    tail = text.splitlines()[-300:]
    head = text.splitlines()[:5]
    found: dict[str, str] = {}
    for line in tail:
        if not line.startswith(";") or "=" not in line:
            continue
        key, value = line[1:].split("=", 1)
        found[key.strip()] = value.strip()

    g = found.get("total filament used [g]") or found.get("filament used [g]")
    mm = found.get("filament used [mm]")
    t = found.get("estimated printing time (normal mode)")
    if g is None or t is None:
        raise SlicerError("В G-code нет итогов (граммы или время). Слайсер отработал не до конца?")

    version = ""
    for line in head:
        if "generated by" in line.lower():
            version = line.lstrip("; ").strip()
            break

    return {
        "print_time_s": parse_time(t),
        # многоматериальный G-code: «1.23, 0.00» — складываем
        "filament_g": round(sum(float(v) for v in g.split(",")), 2),
        "filament_mm": round(sum(float(v) for v in mm.split(",")), 1) if mm else 0.0,
        "slicer_version": version,
    }


# --- запуск -----------------------------------------------------------------


def slice_model(
    model_path: Path,
    out_dir: Path,
    material: str,
    units: str = "mm",
    supports: bool = False,
) -> SliceResult:
    """Запускает слайсер, возвращает время и граммы. G-code остаётся в out_dir."""
    material = material.upper()
    out_dir.mkdir(parents=True, exist_ok=True)
    suffix = "_supports" if supports else ""
    gcode_path = out_dir / f"{material}{suffix}.gcode"
    cmd = build_command(model_path, gcode_path, material, units, supports)

    try:
        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=settings.slice_timeout_s,
            check=False,
        )
    except FileNotFoundError as e:
        raise SlicerError(
            f"Не найден PrusaSlicer: {cmd[0]}. Проверь PRUSA_SLICER_BIN или запусти worker."
        ) from e
    except subprocess.TimeoutExpired as e:
        raise SlicerError(f"Слайсер не уложился в {settings.slice_timeout_s} с.") from e

    if proc.returncode != 0 or not gcode_path.is_file():
        tail = (proc.stderr or proc.stdout or "").strip().splitlines()[-5:]
        raise SlicerError("Слайсер завершился с ошибкой: " + " | ".join(tail))

    parsed = parse_gcode(gcode_path.read_text("utf-8", errors="replace"))
    layer = read_ini_value(profiles_dir() / "print.ini", "layer_height")
    return SliceResult(
        material=material,
        supports=supports,
        layer_height_mm=float(layer) if layer else None,
        **parsed,
    )
